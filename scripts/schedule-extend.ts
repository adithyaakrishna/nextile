// Usage: pnpm schedule:extend [--days=N]
// Appends reviewed, valid puzzles to the schedule in the weekly difficulty rhythm and balances answer positions.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LAUNCH_DAY } from "../src/config";
import { PUBLISHED_LOCK } from "../src/content/lock";
import { PUZZLES } from "../src/content/puzzles";
import { SCHEDULE, type ScheduleEntry } from "../src/content/schedule";
import type { Difficulty } from "../src/engine/difficulty";
import type { Puzzle } from "../src/engine/puzzle";
import { validate } from "../src/engine/validate";
import { addDays, weekdayOf } from "../src/time/day";
import { puzzleFile } from "./lib/puzzles";
import { readProperty, replaceProperty } from "./lib/source";

// Easy on Monday and Tuesday, medium Wednesday to Friday and Sunday, hard on Saturday
const RHYTHM: Record<number, Difficulty> = { 0: "medium", 1: "easy", 2: "easy", 3: "medium", 4: "medium", 5: "medium", 6: "hard" };
const FALLBACKS: Record<Difficulty, Difficulty[]> = {
  easy: ["easy", "medium", "hard"],
  medium: ["medium", "easy", "hard"],
  hard: ["hard", "medium", "easy"],
};

const daysFlag = process.argv.find((a) => a.startsWith("--days="));
const maxDays = daysFlag ? Number(daysFlag.split("=")[1]) : Number.POSITIVE_INFINITY;

const byId = new Map(PUZZLES.map((p) => [p.id, p]));
const scheduled = new Set(SCHEDULE.map((e) => e.id));
const pool = PUZZLES.filter((p) => p.review && !scheduled.has(p.id) && validate(p).errors.length === 0);
const schedule: ScheduleEntry[] = [...SCHEDULE];
const positions = SCHEDULE.map((e) => byId.get(e.id)?.answerIndex ?? -1);

function pick(day: string, previous: Puzzle | undefined): Puzzle | undefined {
  for (const tier of FALLBACKS[RHYTHM[weekdayOf(day)]]) {
    const tierPool = pool.filter((p) => p.difficulty === tier);
    const choice = tierPool.find((p) => p.family !== previous?.family) ?? tierPool[0];
    if (choice) return choice;
  }
  return undefined;
}

function hashOf(s: string): number {
  let h = 2166136261;
  for (const ch of s) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return h >>> 0;
}

function choosePosition(day: string, current: number): number {
  const [a, b] = positions.slice(-2);
  const allowed = [0, 1, 2, 3].filter((pos) => !(a === pos && b === pos));
  const counts = allowed.map((pos) => positions.filter((x) => x === pos).length);
  const fewest = Math.min(...counts);
  const tied = allowed.filter((_, i) => counts[i] === fewest);
  return tied.includes(current) ? current : tied[hashOf(day) % tied.length];
}

// Moves the answer's line inside the choices array so the author's recipe comments survive
function moveAnswer(p: Puzzle, to: number): void {
  const file = puzzleFile(p.id);
  const source = readFileSync(file, "utf8");
  const lines = readProperty(source, "choices").split("\n");
  const tileLines = lines.filter((l) => l.trim().startsWith("{"));
  const [answer] = tileLines.splice(p.answerIndex, 1);
  tileLines.splice(to, 0, answer);
  let i = 0;
  const reordered = lines.map((l) => (l.trim().startsWith("{") ? tileLines[i++] : l)).join("\n");
  writeFileSync(file, replaceProperty(replaceProperty(source, "choices", reordered), "answerIndex", String(to)));
}

let day = schedule.length > 0 ? addDays(schedule[schedule.length - 1].day, 1) : LAUNCH_DAY;
let added = 0;
while (added < maxDays) {
  const previous = byId.get(schedule[schedule.length - 1]?.id ?? "");
  const p = pick(day, previous);
  if (!p) break;
  pool.splice(pool.indexOf(p), 1);
  if (PUBLISHED_LOCK[day]) throw new Error(`${day} is already locked; refusing to reschedule it`);
  const position = choosePosition(day, p.answerIndex);
  if (position !== p.answerIndex) moveAnswer(p, position);
  positions.push(position);
  schedule.push({ day, id: p.id });
  day = addDays(day, 1);
  added++;
}

const body = schedule.map((e) => `  { day: "${e.day}", id: "${e.id}" },`).join("\n");
writeFileSync(
  join(process.cwd(), "src/content/schedule.ts"),
  `// Generated by \`pnpm schedule:extend\`. Never edit past dates by hand.
import "server-only";

export interface ScheduleEntry {
  day: string;
  id: string;
}

export const SCHEDULE: readonly ScheduleEntry[] = [
${body}
];
`,
);
console.log(`Added ${added} days. The schedule now runs ${schedule[0]?.day ?? "—"} → ${schedule.at(-1)?.day ?? "—"} (${schedule.length} days); ${pool.length} reviewed puzzles remain unscheduled.`);
